export class ClaudeProvider implements AgentProvider {
  readonly id = 'claude';
  readonly label = 'Claude Code';
  readonly binary = 'claude';
  readonly capabilities = CLAUDE_CAPABILITIES;

  /** Live catalogue, or `null` for "pins only". See `useCatalogue`. */
  private _catalogue: ModelCatalogue | null = null;

  /**
   * Bind the live model catalogue AFTER construction — the same late-binding
   * seam, for the same reason, as `OpencodeProvider.useKeySource`
   * (`opencode.ts:414-429`): the provider registry is built during boot's
   * runtime-materialisation phase, before anything that could own a cache
   * exists, and reordering those phases buys nothing.
   *
   * An UNBOUND adapter behaves exactly like it did before this seam existed:
   * pinned list, pinned default, no network. That is what makes every unit test
   * hermetic BY CONSTRUCTION rather than by remembering not to install one —
   * and it is why the tests that pin model ids need no `catalogue` awareness.
   */
  useCatalogue(catalogue: ModelCatalogue | null): void {
    this._catalogue = catalogue;
  }

  models(): readonly ProviderModel[] {
    return this._catalogue?.models('claude', CLAUDE_MODELS) ?? CLAUDE_MODELS;
  }

  defaults(): { model: string; effort: EffortLevel; permissionMode: PermissionMode } {
    return {
      model:
        this._catalogue?.defaultModel('claude', BUILTIN_PROVIDER_DEFAULT_MODELS.claude) ??
        BUILTIN_PROVIDER_DEFAULT_MODELS.claude,
      effort: 'xhigh',
      permissionMode: 'bypassPermissions',
    };
  }

  /**
   * PHASE A — per-session `CLAUDE_CONFIG_DIR`
   * (`<claudeRuntimeDir>/sessions/<id>/`) with a `settings.json` injecting the
   * `Notification` hook (plan §13, spike H6).
   *
   * The hook payload arrives on stdin per Anthropic's Claude Code spec
   * (`{ session_id, transcript_path, cwd, hook_event_name, message }` — see
   * spike report §5). We read stdin via `cat` then re-encode it in JSON to
   * a single-line POST body that includes our orch_id / session_id (the ones
   * Claude doesn't know about — Anthropic's session_id is its own internal id).
   *
   * Returns the path of the config dir (or null if not configured).
   * `cleanupPaths` is empty: claude's per-session dir is deliberately left in
   * place (it holds symlinks and a trust seed, nothing that grows).
   */
  prepareSessionConfig(req: SessionConfigRequest): SessionConfigResult {
    return { configDir: this._prepareConfigDir(req), cleanupPaths: [] };
  }

  private _prepareConfigDir(req: SessionConfigRequest): string | null {
    if (!req.hookToken || !req.mainHttpPort || !req.runtimeRoot) return null;
    const runtimeRoot = req.runtimeRoot;
    const isSsh = req.transport === 'ssh';
    try {
      // Phase 5: runtimeRoot is the resolved <claudeRuntimeDir> (typically
      // `<dataDir>/.claude-runtime`). The per-session config dir is a sibling
      // under `sessions/`. We mirror Phase 4's path layout exactly (sessions
      // live under the runtime root).
      const cfgDir = path.join(runtimeRoot, 'sessions', req.sessionId);
      fs.mkdirSync(cfgDir, { recursive: true, mode: 0o700 });
      try {
        fs.chmodSync(cfgDir, 0o700);
      } catch {
        /* best-effort */
      }
      // Refresh the host-volatile files (`.credentials.json` + `.claude.json`)
      // from the RO source mount before symlinking. The boot-time copy is
      // gated by the dir-mtime marker, which doesn't notice in-place edits
      // of these files (host claude rotates OAuth tokens in-place). Without
      // this, every team created after a host token rotation would inherit
      // a stale runtime `.credentials.json` and the PTY would land on the
      // interactive `/login` prompt.
      //
      // SSH transport: the container never reads or copies host credentials —
      // the host claude resolves its own `~/.claude/.credentials.json`
      // directly via the per-session symlink. Skip the refresh entirely.
      if (req.sourceDir && !isSsh) {
        try {
          const refresh = refreshClaudeSharedFiles({
            sourceDir: req.sourceDir,
            runtimeDir: runtimeRoot,
            claudeJsonSource: req.siblingSource ?? null,
          });
          if (refresh.credentials === 'lifted' || refresh.claudeJson === 'lifted') {
            log.info({
              event: 'session.shared_refresh',
              sessionId: req.sessionId,
              credentials: refresh.credentials,
              claudeJson: refresh.claudeJson,
            });
          }
        } catch (err) {
          log.warn({
            event: 'session.shared_refresh_failed',
            sessionId: req.sessionId,
            error: err instanceof Error ? err.message : String(err),
          });
        }
      }
      // Phase 5: symlink shared Claude state into the per-session dir so the
      // per-session CLAUDE_CONFIG_DIR sees the credentials, history, etc.
      // from the runtime copy. We pick the union of subdirectories Claude
      // is known to look at (spike H7 inventory). Best-effort: if the
      // shared dir doesn't have a given subentry, we skip the symlink.
      this._linkSharedState(req, runtimeRoot, cfgDir);
      // Pre-accept the trust + project-onboarding dialogs for this cwd so
      // the PTY doesn't wedge on first spawn. Must run AFTER the symlink
      // pass (which is scoped to skip `.claude.json`) and BEFORE any
      // settings.json write so the dialog state is in place before the
      // claude CLI reads it.
      //
      // SSH mode: the container-side `<runtimeDir>/.claude.json` is never
      // populated (claude-init is a no-op). Read the host's `.claude.json`
      // directly through the RO source mount (`siblingSource`, typically
      // `/claude-source.json`, or `<sourceDir>.json` as fallback) so
      // onboarding / userID / theme survive.
      const sshJsonFallback =
        req.sourceDir && req.sourceDir.length > 0 ? `${req.sourceDir}.json` : null;
      const claudeJsonSrc = isSsh
        ? (req.siblingSource ?? sshJsonFallback)
        : path.join(runtimeRoot, '.claude.json');
      this._seedClaudeJsonTrust(req, cfgDir, claudeJsonSrc);
      const shellCmd = buildNotificationHookCommand({
        orchestratorId: req.orchestratorId,
        sessionId: req.sessionId,
        hookToken: req.hookToken,
        mainHttpPort: req.mainHttpPort,
      });
      // Pre-accept the "bypass permissions mode" disclaimer at the
      // user-settings level. claude-code 2.1.143 migrates the legacy
      // `.claude.json#bypassPermissionsModeAccepted` flag into
      // `userSettings.skipDangerousModePermissionPrompt` on first launch
      // and then deletes the source field — the runtime check that opens
      // the interactive disclaimer widget reads ONLY the user/local/flag/
      // policy settings (`qu()` in the bundled CLI). Setting it directly
      // here makes the pre-acceptance survive the migration and keeps
      // the per-session `.claude.json` seed effective as a fallback for
      // older builds.
      //
      // `tui: 'default'` pins the classic inline renderer. claude-code
      // 2.1.201 shows a "Try the new fullscreen renderer?" upsell dialog
      // whenever `settings.tui` is undefined; inside a headless PTY the
      // injected wake-up text can accept it, after which claude re-execs
      // itself in fullscreen mode whose constant repaints make the session
      // look permanently busy (idle detection never fires, inbox signals
      // are never delivered). Any defined `tui` value suppresses the
      // dialog entirely.
      const settings = {
        skipDangerousModePermissionPrompt: true,
        tui: 'default',
        hooks: {
          Notification: [
            {
              matcher: '',
              hooks: [
                {
                  type: 'command',
                  command: shellCmd,
                },
              ],
            },
          ],
        },
      };
      const settingsPath = path.join(cfgDir, 'settings.json');
      // `writeSessionFile`, not `writeFileSync`: this dir also holds symlinks
      // into the shared `~/.claude`, and a link at `settings.json` would carry
      // this session's hook token into the operator's own file.
      writeSessionFile(settingsPath, JSON.stringify(settings, null, 2));
      return cfgDir;
    } catch (err) {
      log.warn({
        event: 'session.settings_failed',
        sessionId: req.sessionId,
        error: err instanceof Error ? err.message : String(err),
      });
      return null;
    }
  }

  /**
   * Phase 5: symlink the union of Claude-known state subentries from the
   * shared root into the per-session config dir. This lets
   * `CLAUDE_CONFIG_DIR=<sessions/<id>>` see the credentials + history while
   * keeping `settings.json` per-session (so each session can carry its own
   * Notification hook context).
   *
   * The list comes from the spike report H7 inventory — we don't try to be
   * exhaustive (Claude may add new files at runtime); anything missing is
   * just not symlinked. Per-session writes that would land on a brand-new
   * shared file land directly in the session dir — no shared corruption.
   *
   * SSH transport: symlink targets must be HOST paths so the remote claude
   * resolves them in its own namespace. We cannot stat the target from the
   * container side (the host `~/.claude/` is not mounted RW in SSH mode);
   * create the links best-effort and let claude silently skip missing entries
   * on the host.
   */
  private _linkSharedState(
    req: SessionConfigRequest,
    runtimeRoot: string,
    cfgDir: string,
  ): void {
    if (req.transport === 'ssh') {
      if (!req.hostSharedDir) return;
      linkSharedState({
        targetRoot: req.hostSharedDir,
        configDir: cfgDir,
        entries: CLAUDE_SHARED_ENTRIES,
        existsCheck: false,
        onError: (info) => {
          log.warn({
            event: 'session.shared_link_ssh_failed',
            sessionId: req.sessionId,
            entry: info.entry,
            target: info.target,
            error: info.error,
          });
        },
      });
      return;
    }
    linkSharedState({
      targetRoot: runtimeRoot,
      configDir: cfgDir,
      entries: CLAUDE_SHARED_ENTRIES,
      existsCheck: true,
      onError: (info) => {
        log.warn({
          event: 'session.shared_link_failed',
          sessionId: req.sessionId,
          entry: info.entry,
          error: info.error,
        });
      },
    });
  }

  /**
   * Pre-accept the trust dialog and project-onboarding prompts for this
   * session's `cwd` by writing a per-session `.claude.json` under
   * `<cfgDir>/.claude.json`. Without this, the claude CLI opens the
   * interactive "Do you trust the files in this folder?" widget on first
   * spawn into a never-before-seen cwd and wedges the PTY.
   *
   * Strategy: read the lifted runtime `.claude.json` so we preserve
   * `hasCompletedOnboarding`, `userID`, theme, etc., merge in
   * `projects[<cwd>]` with the trust flags set, then write the result
   * as a REGULAR file (not a symlink) into the per-session config dir.
   * If the runtime file is missing or unreadable we fall back to a
   * minimal seed sufficient to silence the prompt.
   *
   * Why a per-session file (not a one-shot edit of the runtime copy):
   *   - We don't want claude's mid-session writes (lastSessionId, lastCost,
   *     etc.) leaking across sessions through the shared file.
   *   - Avoids racing with concurrent spawns also mutating the same path.
   */
  private _seedClaudeJsonTrust(
    req: SessionConfigRequest,
    cfgDir: string,
    claudeJsonSrc: string | null,
  ): void {
    const dest = path.join(cfgDir, '.claude.json');
    // Projects in `~/.claude.json` are keyed by absolute path. In SSH mode the
    // remote claude resolves the cwd as a host path; the trust entry must use
    // the same key or claude re-opens the trust dialog.
    const projectKey = req.paths.workspace(req.cwd);

    let base: Record<string, unknown>;
    try {
      if (!claudeJsonSrc) throw new Error('no .claude.json source path');
      const raw = fs.readFileSync(claudeJsonSrc, 'utf8');
      const parsed: unknown = JSON.parse(raw);
      base =
        parsed && typeof parsed === 'object' && !Array.isArray(parsed)
          ? (parsed as Record<string, unknown>)
          : { hasCompletedOnboarding: true };
    } catch {
      // Missing or unreadable lifted file (dev mode without claude-init,
      // or a partial container). The minimal seed below is enough — claude
      // will create the rest of its state on its own.
      base = { hasCompletedOnboarding: true };
    }

    // Pre-accept the global "bypass permissions mode disclaimer" so the
    // CLI doesn't open an interactive disclaimer widget on first spawn
    // under `--permission-mode bypassPermissions`. The field is a top-level
    // boolean in `.claude.json` checked by the CLI before launching in
    // bypass mode (verified against claude-code 2.1.143 — the binary
    // references `E$().bypassPermissionsModeAccepted` from its arg parser).
    // We set it unconditionally: the flag means "the user has seen the
    // disclaimer once"; it's a no-op for other modes.
    base.bypassPermissionsModeAccepted = true;

    const projectsRaw = base.projects;
    const projects: Record<string, Record<string, unknown>> =
      projectsRaw && typeof projectsRaw === 'object' && !Array.isArray(projectsRaw)
        ? (projectsRaw as Record<string, Record<string, unknown>>)
        : {};
    const existing = projects[projectKey];
    const cwdEntry: Record<string, unknown> =
      existing && typeof existing === 'object' && !Array.isArray(existing)
        ? { ...existing }
        : {};
    cwdEntry.hasTrustDialogAccepted = true;
    cwdEntry.hasCompletedProjectOnboarding = true;
    cwdEntry.hasClaudeMdExternalIncludesApproved = true;
    if (existing == null) {
      // Brand-new project entry — populate the empty containers claude
      // expects so it doesn't re-run any per-project initialisation.
      cwdEntry.allowedTools = [];
      cwdEntry.mcpContextUris = [];
      cwdEntry.mcpServers = {};
      cwdEntry.enabledMcpjsonServers = [];
      cwdEntry.disabledMcpjsonServers = [];
    }
    projects[projectKey] = cwdEntry;
    base.projects = projects;

    // `writeSessionFile` removes whatever is at `dest` first (typically nothing
    // now that `.claude.json` is excluded from the shared entries, but a stale
    // symlink from a previous server version would otherwise be FOLLOWED and
    // corrupt the shared runtime file).
    try {
      writeSessionFile(dest, JSON.stringify(base, null, 2));
    } catch (err) {
      log.warn({
        event: 'session.claude_json_seed_failed',
        sessionId: req.sessionId,
        cwd: req.cwd,
        error: err instanceof Error ? err.message : String(err),
      });
    }
  }

  /**
   * PHASE B.1 — claude reads a standalone `mcp.json` handed to it via
   * `--mcp-config=<path>`, so there is nothing to merge into the per-session
   * config dir. Throws on a read-only runtime dir; `Session` downgrades that
   * to "run without MCP" rather than failing the spawn.
   */
  writeMcpConfig(req: McpWriteRequest): McpWriteResult {
    return writeSessionMcpConfig({
      runtimeDir: req.runtimeDir,
      orchestratorId: req.orchestratorId,
      sessionId: req.sessionId,
      sessionSecret: req.sessionSecret,
      mcpHost: req.mcpHost,
      mcpPort: req.mcpPort,
    });
  }

  removeMcpConfig(req: McpCleanupRequest): void {
    removeSessionMcpConfig({
      runtimeDir: req.runtimeDir,
      orchestratorId: req.orchestratorId,
      sessionId: req.sessionId,
    });
  }

  /**
   * PHASE B.2 — pure. Both paths handed to claude (`CLAUDE_CONFIG_DIR` and
   * `--mcp-config`) live under the container's dataDir bind mount, so they go
   * through the `data` mapper; the cwd is `Session`'s business.
   */
  buildSpawn(req: SpawnRequest): PreparedSpawn {
    const args = buildClaudeArgs({
      model: req.model,
      effort: req.effort,
      permissionMode: req.permissionMode,
      initialPrompt: req.initialPrompt,
      preamble: req.preamble,
      resumeNotice: req.resumeNotice,
      mcpConfigPath: req.mcpConfigPath ? req.paths.data(req.mcpConfigPath) : null,
    });
    const env: Record<string, string> = {};
    if (req.configDir) env.CLAUDE_CONFIG_DIR = req.paths.data(req.configDir);
    // Force MCP tools INLINE (no ToolSearch deferral). claude 2.1.201
    // defers MCP tools behind a ToolSearch meta-tool in interactive
    // mode; smaller models (haiku) fail the ToolSearch→call dance and
    // effectively lose team-comms (observed 2026-07-04: sentinel
    // "unable to invoke MCP tools even after ToolSearch loads their
    // schemas"). "false" pins the pre-2.1.2xx inline behaviour.
    env.ENABLE_TOOL_SEARCH = 'false';
    return { command: this.binary, args, env };
  }

  /** `/clear` and `/compact` are claude's own slash commands — identity. */
  contextResetLine(cmd: ContextResetCommand, instructions?: string): string | null {
    return instructions ? `${cmd} ${instructions}` : cmd;
  }

  /**
   * IDENTITY — the preamble keeps the canonical dotted names for claude, and
   * that is a deliberate choice rather than "claude does not rename".
   *
   * Claude Code DOES expose an MCP tool as `mcp__<server>__<tool>`; the literal
   * `mcp__server__tool` is in the shipped binary (grep the 2.1.220 executable),
   * so the true model-facing name here is `mcp__team-comms__team.whoami`.
   *
   * We still hand the agent `team.whoami`, because:
   *
   *   1. it is the only rendering with a production track record — every claude
   *      team this server has ever run got the dotted names and reached its
   *      mailbox (the MCP server's `logCall` lines prove the calls land), so the
   *      model reconciles the canonical name against the tool list Claude Code
   *      already injects into its own system prompt;
   *   2. switching the live path would change the text of every claude preamble
   *      for a benefit nothing has measured. That is a decision to take on its
   *      own evidence, not a side effect of making the OTHER three adapters
   *      honest.
   *
   * If it is ever revisited, `mcp__${server}__${tool}` is the form to use and
   * `mcp-config.ts` owns the `team-comms` server name.
   */
  mcpToolName(logicalName: string): string {
    return logicalName;
  }

  initRuntime(opts: RuntimeInitOptions): RuntimeInitOutcome {
    const r = initClaudeRuntime({
      sourceDir: opts.sourceDir,
      runtimeDir: opts.runtimeDir,
      claudeJsonSource: opts.siblingSource ?? null,
    });
    return {
      initialized: r.initialized,
      copied: r.copied,
      skipReason: r.skipReason ?? null,
      entriesCopied: r.entriesCopied ?? null,
      sibling: r.claudeJson ?? null,
      siblingSource: r.claudeJsonSource ?? null,
    };
  }

  refreshSharedFiles(opts: RuntimeInitOptions): void {
    refreshClaudeSharedFiles({
      sourceDir: opts.sourceDir,
      runtimeDir: opts.runtimeDir,
      claudeJsonSource: opts.siblingSource ?? null,
    });
  }

  /**
   * `claude --version` where the agent would actually run: in-container under
   * the local transport, on the host through the login shell under SSH.
   *
   * Deliberately NOT an auth check. A `claude` that is installed but logged out
   * still counts as available — the operator's fix for that is a `/login` on
   * the host, and reporting it here would conflate "you have no CLI" with "your
   * token expired", which need different actions.
   */
  probe(ctx: ProviderProbeContext): Promise<ProviderAvailability> {
    return probeCliBinary({ ...ctx, binary: this.binary });
  }
}

