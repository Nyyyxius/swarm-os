/**
 * Option A memory integration (docs/graphify-integration.md §6, decision Q2) —
 * the code graph becomes DISCOVERABLE inside the shared Obsidian memory.
 *
 * For every enabled scope the indexer maintains an auto-managed note
 * `codegraph-<scopeId>` (top hubs + counts + how to query it live), and one hub
 * note `codegraph` that wikilinks to them all. These are the swarm-os-GENERATED
 * wikilink layer (graphify's own report emits none — P0 correction a), so an
 * agent doing `memory.search("token validation")` can stumble onto the code map
 * and drill in via `codegraph.*`.
 *
 * Server-side writes (no MCP session): `MemoryStore.upsertNote` takes an explicit
 * `createdBy`/`team`, so we stamp `createdBy: 'system:codegraph'`, `team: null`
 * and `metadata: { managed, scope, source }`. Everything is best-effort and
 * wrapped so a memory hiccup can NEVER affect indexing. Writes are idempotent:
 * we only upsert when the rendered body/description actually changed, so a
 * steady state produces zero memory churn (and zero `memory.node_updated`
 * events) sweep after sweep.
 */

import { withModule } from '../../logger.js';
import type { MemoryStore } from '../memory/store.js';
import type { GraphStore, CodegraphScope } from './store.js';
import { graphJsonPath } from './graphify.js';
import { topHubs } from './query.js';

const log = withModule('codegraph.memory');

/** Slug of the deployment-wide hub note. */
export const HUB_NOTE_NAME = 'codegraph';
/** Provenance stamped on every managed note (not a real session). */
export const CODEGRAPH_AUTHOR = 'system:codegraph';

const MANAGED_BANNER = '> Auto-generated by the code-graph indexer — do not edit by hand.';

export function scopeNoteName(scopeId: string): string {
  return `${HUB_NOTE_NAME}-${scopeId}`;
}

function isoOrNever(ms: number | null): string {
  if (!ms) return 'never';
  try {
    return new Date(ms).toISOString();
  } catch {
    return 'never';
  }
}

/** Render the per-scope note body (deterministic → drives idempotency). */
export function renderScopeNoteBody(scope: CodegraphScope, indexDir: string): string {
  const hubs = topHubs(graphJsonPath(indexDir), 8);
  const lines: string[] = [
    MANAGED_BANNER,
    '',
    `# Code graph — ${scope.id}`,
    '',
    `- **Kind:** ${scope.kind}`,
    `- **Path:** ${scope.path}`,
    `- **Nodes / edges:** ${scope.nodeCount} / ${scope.edgeCount}`,
    `- **Last indexed:** ${isoOrNever(scope.lastIndexedAt)}`,
    '',
  ];
  if (hubs.length > 0) {
    lines.push('## Top hubs (most connected)', '');
    for (const h of hubs) {
      const loc = h.file ? `${h.file}${h.line != null ? `:${h.line}` : ''}` : 'unknown';
      lines.push(`- \`${h.label}\` — ${loc} (${h.degree} edges)`);
    }
    lines.push('');
  }
  lines.push(
    'Query this map live via `codegraph.search` / `codegraph.explain` / `codegraph.path` ' +
      `with \`scope="${scope.id}"\`.`,
    '',
    `Part of [[${HUB_NOTE_NAME}]].`,
    '',
  );
  return lines.join('\n');
}

/**
 * Render the hub note body linking every INDEXED scope. We list only scopes with
 * a note that actually exists (`lastIndexedAt != null`) so the hub never carries
 * a dangling wikilink to a not-yet-created scope note.
 */
export function renderHubNoteBody(scopes: CodegraphScope[]): string {
  const enabled = scopes
    .filter((s) => s.enabled && s.lastIndexedAt != null)
    .sort((a, b) => (a.id < b.id ? -1 : 1));
  const lines: string[] = [
    MANAGED_BANNER,
    '',
    '# Code graph (Graphify)',
    '',
    'Live, auto-maintained maps of the first-party code in this deployment, built',
    'on-device by Graphify. Query any of them with `codegraph.search` /',
    '`codegraph.explain` / `codegraph.path`.',
    '',
    '## Indexed scopes',
    '',
  ];
  if (enabled.length === 0) {
    lines.push('_No code scope is currently indexed._', '');
  } else {
    for (const s of enabled) {
      lines.push(`- [[${scopeNoteName(s.id)}]] — ${s.kind} · ${s.nodeCount} nodes / ${s.edgeCount} edges`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/**
 * Idempotent upsert: write only when the rendered body OR description differs
 * from what's already stored. Returns true when a write happened. Never throws.
 */
function upsertIfChanged(
  memory: MemoryStore,
  name: string,
  description: string,
  body: string,
  scopeId: string | null,
): boolean {
  try {
    const existing = memory.readNote(name);
    if (existing && existing.body === body && existing.description === description) {
      return false; // steady state — no churn
    }
    memory.upsertNote({
      name,
      description,
      type: 'reference',
      body,
      createdBy: CODEGRAPH_AUTHOR,
      team: null,
      metadata: {
        managed: true,
        source: 'codegraph',
        ...(scopeId ? { scope: scopeId } : {}),
      },
    });
    return true;
  } catch (err) {
    log.warn({ event: 'codegraph.note_write_failed', name, error: String(err) });
    return false;
  }
}

/**
 * Maintains the `codegraph` hub + per-scope notes in the shared memory. All
 * methods no-op when `memory` is absent (memory subsystem off) and never throw.
 */
export class CodegraphMemoryNotes {
  constructor(
    private readonly memory: MemoryStore | null | undefined,
    private readonly store: GraphStore,
  ) {}

  get enabled(): boolean {
    return !!this.memory;
  }

  /** Write/refresh one scope's note after a successful index. */
  syncScope(scopeId: string): void {
    if (!this.memory) return;
    const scope = this.store.getScope(scopeId);
    if (!scope || !scope.enabled) return;
    const body = renderScopeNoteBody(scope, this.store.indexDirFor(scopeId));
    const description = `Code map for ${scope.kind} scope ${scope.id} (${scope.nodeCount} nodes).`;
    upsertIfChanged(this.memory, scopeNoteName(scopeId), description, body, scopeId);
  }

  /** Delete a scope's note (scope disabled or removed). Never throws. */
  removeScope(scopeId: string): void {
    if (!this.memory) return;
    try {
      const name = scopeNoteName(scopeId);
      if (this.memory.readNote(name)) this.memory.deleteNote(name);
    } catch (err) {
      log.warn({ event: 'codegraph.note_delete_failed', scopeId, error: String(err) });
    }
  }

  /** Rebuild the hub note from the current enabled-scope set. */
  refreshHub(): void {
    if (!this.memory) return;
    const scopes = this.store.listScopes();
    const body = renderHubNoteBody(scopes);
    const description = 'Index of the auto-maintained code graphs (Graphify) in this deployment.';
    upsertIfChanged(this.memory, HUB_NOTE_NAME, description, body, null);
  }
}
